#!/usr/bin/env python3
"""Verify pinned MediaPipe registration anchors and regenerate app linker settings.

Run after Xcode resolves the packages. --sdk-root is its
SourcePackages/artifacts/mediapipetasks directory. No SDK binary is modified.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / 'Vendor/MediaPipeTasks/pose-link-anchors.json'
CONFIG = ROOT / 'config/MediaPipePose.xcconfig'


def digest(path):
    result = hashlib.sha256()
    with path.open('rb') as file:
        for block in iter(lambda: file.read(1024 * 1024), b''):
            result.update(block)
    return result.hexdigest()


def require(condition, message):
    if not condition:
        raise SystemExit(message)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sdk-root', type=Path, required=True)
    parser.add_argument('--write-config', action='store_true')
    args = parser.parse_args()
    catalog = json.loads(CATALOG.read_text())
    anchors = catalog['anchors']
    require(len({row['symbol'] for row in anchors}) == len(anchors), 'Duplicate anchor')
    expected = (
        '// Generated by scripts/verify-mediapipe-pose-linkage.py --write-config.\n'
        '// MediaPipe 1.2.2 CPU pose registration units; do not remove individual symbols.\n'
        '// See Vendor/MediaPipeTasks/UPSTREAM.txt before changing SDKs or task types.\n'
        '// App only: test bundles resolve these symbols through their host.\n'
        'OTHER_LDFLAGS = $(inherited) \\\n'
        + ' \\\n'.join('    -Xlinker -u -Xlinker ' + row['symbol'] for row in anchors) + '\n'
    )
    for arch, sha256 in catalog['task_graph_sha256'].items():
        library = (args.sdk_root / 'MediaPipeTaskGraphsBinary' /
                   'MediaPipeTaskGraphs_library.xcframework' / arch /
                   'MediaPipeTaskGraphs_library.a')
        require(digest(library) == sha256, f'{arch}: SDK changed; review dependencies and rerun inference comparisons')
        result = subprocess.run(['xcrun', 'nm', '-m', '-gU', str(library)],
                                text=True, capture_output=True, check=True)
        definitions = {}
        member = None
        for line in result.stdout.splitlines():
            if line.endswith(':') and not line.startswith(' '):
                member = line[:-1]
            elif re.match(r'^[0-9a-fA-F]+ ', line) and 'non-external' not in line:
                definitions.setdefault(line.split()[-1], set()).add(member)
        for row in anchors:
            members = definitions.get(row['symbol'], set())
            require(members == {row['member']}, f"{arch}: anchor must identify exactly {row['member']}; found {members}")
        print(f'{arch}: verified {len(anchors)} unique registration anchors and pinned archive hash')
    if args.write_config:
        CONFIG.write_text(expected)
        print(f'Generated {CONFIG.relative_to(ROOT)}')
    else:
        require(CONFIG.read_text() == expected, 'Regenerate MediaPipePose.xcconfig with --write-config')
        print('App linker configuration matches the verified anchor catalog')


if __name__ == '__main__':
    main()
